def _sanitize_stub(stub: str) -> str:
    """Post-process litgen stub to fix invalid Python syntax."""
    # Fix litgen generating invalid Python types for C++ return types
    stub = stub.replace("-> signed int int:", "-> int:")
    stub = stub.replace("-> int int:", "-> int:")
    stub = stub.replace("-> unsigned int int:", "-> int:")
    # Fix C++ type names that are not valid Python
    stub = stub.replace("-> hash_t:", "-> int:")
    stub = stub.replace("-> vec_basic:", "-> list:")
    stub = stub.replace("-> umap_basic_num:", "-> dict:")
    stub = stub.replace("-> map_basic_basic:", "-> dict:")
    stub = stub.replace(": integer_class", ": int")
    stub = stub.replace(": rational_class", ": int")
    stub = stub.replace("-> integer_class:", "-> int:")
    stub = stub.replace("-> rational_class:", "-> int:")
    stub = stub.replace(": map_basic_basic", ": dict")
    stub = stub.replace(": vec_basic", ": list")
    stub = stub.replace(": set_basic", ": set")
    stub = stub.replace("-> set_basic:", "-> set:")
    stub = stub.replace(": set_set", ": set")
    stub = stub.replace("-> set_set:", "-> set:")
    stub = stub.replace(": unsigned", ": int")
    stub = stub.replace("-> unsigned:", "-> int:")
    # Fix invalid escape sequences in docstrings from C++ comments
    # (\p from \param, \c from \class, \return, \file, etc.)
    def _fix_escape_sequences(match: re.Match) -> str:
        s = match.group(0)
        # Double any single backslashes that aren't already doubled
        # and aren't followed by a recognized Python escape char
        return re.sub(r"(?<!\\)\\(?![\\nrtbfav'u\"0-9xU\n])", r"\\\\", s)

    stub = re.sub(r'""".*?"""', _fix_escape_sequences, stub, flags=re.DOTALL)
    return stub


# Intentional comments that must survive stripping.  Anything matching these
# exact strings is kept verbatim (they are injected *after* this filter runs,
# but we list them here so the predicate is self-documenting).
_INTENTIONAL_COMMENTS = frozenset({
    "# Manually-bound classes",
    "# --- Manually-bound function stubs ---",
})


def _strip_echoed_comments(stub: str) -> str:
    """Remove litgen-echoed C++ comments and collapse blank-line runs.

    Applied to the litgen-generated stub *before* manual stub injection, so
    intentional markers added later are unaffected.  We still check against
    ``_INTENTIONAL_COMMENTS`` as a safety net.
    """
    out_lines: list[str] = []
    prev_blank = False
    for line in stub.splitlines():
        stripped = line.strip()

        # Collapse runs of blank lines to a single blank line.
        if not stripped:
            if not prev_blank:
                out_lines.append("")
                prev_blank = True
            continue
        prev_blank = False

        # Never strip intentional markers.
        if stripped in _INTENTIONAL_COMMENTS:
            out_lines.append(line)
            continue

        # Strip echoed C++ location comments: "# some/path.h:42"
        if re.match(r"^#\s*\S+\.\w+:\d+\s*$", stripped):
            continue

        # Strip lines that are entirely a "# /* ... */" echoed C++ signature.
        # (litgen wraps the original C++ signature in /* ... */ when
        # original_signature_flag_show is on; even with it off, stray
        # passthrough can occur.)
        if stripped.startswith("# /*") and stripped.endswith("*/"):
            continue

        # Strip standalone lines that are just a bare C++ "//" comment echoed
        # verbatim, e.g.  "// forward declaration" -> "# // forward declaration"
        if re.match(r"^#\s*//", stripped):
            continue

        out_lines.append(line)

    return "\n".join(out_lines) + "\n"


