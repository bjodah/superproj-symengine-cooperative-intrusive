def _inheritance_callback(cls: AdaptedClass, generated_code_type: litgen.GeneratedCodeType) -> list[str]:
    name = cls.cpp_element().class_name
    if name not in _SYMENTITY_HIERARCHY:
        return []
    base = _SYMENTITY_HIERARCHY[name]
    if generated_code_type == litgen.GeneratedCodeType.stub:
        return [base]
    return [f"SymEngine::{base}"]


def generate(config_yaml_path: str, dump_srcml: bool = False, output_dir: str | None = None) -> None:
    config_path = Path(config_yaml_path)
    if not config_path.is_absolute():
        config_path = Path.cwd() / config_path

    with open(config_path) as f:
        config = yaml.safe_load(f).get("modules", {})

    for module_name, module in config.items():
        options = litgen.LitgenOptions()
        options.use_nanobind()
        options.python_run_black_formatter = False
        options.python_convert_to_snake_case = False
        options.namespaces_root = ["SymEngine"]

        # Determinism: suppress litgen comment/location passthrough into stubs.
        # Prevents "# header.h:42" location markers (non-deterministic paths).
        # (These are already the default, but set explicitly for documentation.)
        options.original_location_flag_show = False
        # Prevents original C++ signature echoed as "# void fn(...) /* original C++ signature */".
        options.original_signature_flag_show = False
        # NOTE: python_reproduce_cpp_layout is left at its default (True) because
        # the .replace() patterns for injecting is_* methods depend on the C++
        # blank-line layout.  Blank-line determinism is handled by
        # _strip_echoed_comments() which collapses blank-line runs.
        # Strip blank lines inside multi-line doc-comments.
        options.python_strip_empty_comment_lines = True

        options.srcmlcpp_options.code_preprocess_function = preprocess_header

        # Keep narrow: no templates, no raw members
        options.class_template_options.add_ignore(r".*")
        options.fn_template_options.add_ignore(r".*")
        options.member_exclude_by_name__regex = r".*"

        # Custom adapter: pass-through for RCP<const Basic> (Phase 6)
        options.fn_custom_adapters = [adapt_rcp_basic]
        options.class_custom_inheritance__callback = _inheritance_callback

        # Per-module excludes from YAML
        class_excludes = module.get("class_exclude", [])
        if class_excludes:
            options.class_exclude_by_name__regex = "|".join(class_excludes)

        fn_excludes = [
            *module.get("fn_exclude", []),
            *python_excluded_names(_BINDING_SPEC),
        ]
        if fn_excludes:
            options.fn_exclude_by_name__regex = "|".join(fn_excludes)

        # Concatenate headers
        source = ""
        for header in module["headers"]:
            header_path = Path(header)
            if not header_path.is_absolute():
                header_path = Path.cwd() / header
            if not header_path.exists():
                print(f"WARNING: header not found: {header_path}")
                continue
            with open(header_path) as fh:
                source += fh.read() + "\n"

        if not source:
            print(f"WARNING: no source for module {module_name}")
            continue

        if dump_srcml:
            import srcmlcpp

            processed = preprocess_header(source)
            xml = srcmlcpp.code_to_srcml_wrapper(
                options.srcmlcpp_options, processed
            )
            print(xml.str_xml(beautify=True))
            return

        generated = litgen.generate_code(options, source)

        # Resolve output paths
        if output_dir is not None:
            out_base = Path(output_dir)
            pydef_path = out_base / Path(module["pydef_path"]).name
            stub_path = out_base / Path(module["stub_path"]).name
        else:
            pydef_path = Path(module["pydef_path"])
            stub_path = Path(module["stub_path"])
            if not pydef_path.is_absolute():
                pydef_path = config_path.parent.parent / pydef_path
            if not stub_path.is_absolute():
                stub_path = config_path.parent.parent / stub_path

        pydef_path.parent.mkdir(parents=True, exist_ok=True)
        stub_path.parent.mkdir(parents=True, exist_ok=True)

        # Write binding code (glue_code + pydef_code)
        with open(pydef_path, "w") as out:
            out.write(generated.glue_code)
            out.write(generated.pydef_code)

        # Write stub (post-process to fix litgen type issues)
        with open(stub_path, "w") as out:
            # Prepend imports and forward-declared base classes
            out.write(_STUB_HEADER)
            stub_text = _sanitize_stub(generated.stub_code)
            # Re-inject is_* member methods that fn_exclude removed
            # (fn_exclude was needed to suppress free tribool is_* from number.h)
            _integer_is_methods = (
                "    def is_zero(self) -> bool:\n"
                "        pass\n"
                "    def is_minus_one(self) -> bool:\n"
                "        pass\n"
                "    def is_positive(self) -> bool:\n"
                "        pass\n"
                "    def is_negative(self) -> bool:\n"
                "        pass\n"
                "    def is_complex(self) -> bool:\n"
                "        pass\n"
            )
            _rational_is_methods = (
                "    def is_zero(self) -> bool:\n"
                "        pass\n"
                "    def is_minus_one(self) -> bool:\n"
                "        pass\n"
                "    def is_positive(self) -> bool:\n"
                "        pass\n"
                "    def is_negative(self) -> bool:\n"
                "        pass\n"
                "    def is_complex(self) -> bool:\n"
                "        pass\n"
            )
            _old_integer = (
                "    def is_one(self) -> bool:\n"
                '        """! \\return `True` if `1`"""\n'
                "        pass\n\n\n\n"
            )
            _new_integer = (
                "    def is_one(self) -> bool:\n"
                '        """! \\return `True` if `1`"""\n'
                "        pass\n"
                + _integer_is_methods + "\n\n\n"
            )
            result = stub_text.replace(_old_integer, _new_integer, 1)
            if result == stub_text:
                raise RuntimeError(
                    "generate.py: failed to inject Integer is_* stubs — "
                    "anchor pattern not found in litgen output.  "
                    "Check if litgen formatting changed."
                )
            stub_text = result

            _old_rational = (
                "    def is_one(self) -> bool:\n"
                '        """! \\return `True` if `1`"""\n'
                "        pass\n"
                "    def is_int(self) -> bool:\n"
                '        """! \\return `True` if denominator is `1`"""\n'
                "        pass\n"
            )
            _new_rational = (
                "    def is_one(self) -> bool:\n"
                '        """! \\return `True` if `1`"""\n'
                "        pass\n"
                "    def is_int(self) -> bool:\n"
                '        """! \\return `True` if denominator is `1`"""\n'
                "        pass\n"
                + _rational_is_methods
            )
            result = stub_text.replace(_old_rational, _new_rational, 1)
            if result == stub_text:
                raise RuntimeError(
                    "generate.py: failed to inject Rational is_* stubs — "
                    "anchor pattern not found in litgen output.  "
                    "Check if litgen formatting changed."
                )
            stub_text = result
            # Strip echoed C++ comments *after* the .replace() calls above,
            # since those patterns rely on exact blank-line counts from litgen.
            stub_text = _strip_echoed_comments(stub_text)
            out.write(stub_text)

            # Append stubs for manually-bound classes that litgen cannot generate
            _MANUAL_STUBS = [
                "class Erf(Basic): ...",
                "class Erfc(Basic): ...",
                "class LogGamma(Basic): ...",
                "class Beta(Basic): ...",
                "class PolyGamma(Basic): ...",
                "class EmptySet(Set): ...",
                "class UniversalSet(Set): ...",
                "class FiniteSet(Set): ...",
                "class ConditionSet(Set): ...",
                "class ImageSet(Set): ...",
                "class BooleanAtom(Boolean): ...",
                "class And(Boolean): ...",
                "class Or(Boolean): ...",
                "class Not(Boolean): ...",
                "class Xor(Boolean): ...",
                "class Contains(Boolean): ...",
                "class Relational(Boolean): ...",
                "class Equality(Relational): ...",
                "class Unequality(Relational): ...",
                "class LessThan(Relational): ...",
                "class StrictLessThan(Relational): ...",
            ]
            out.write("\n# Manually-bound classes\n")
            for line in _MANUAL_STUBS:
                out.write(line + "\n")

            # Append stubs for manually-bound functions
            out.write(_get_manual_function_stubs())
            out.write(render_python_pyi(_BINDING_SPEC))

        print(f"  Generated: {pydef_path}")
        print(f"  Generated: {stub_path}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("config_yaml_path")
    ap.add_argument(
        "--dump-srcml",
        action="store_true",
        help="Dump the srcML XML tree for the preprocessed headers and exit",
    )
    ap.add_argument(
        "--output-dir",
        default=None,
        help="Write generated files to this directory instead of in-place",
    )
    args = ap.parse_args()
    generate(args.config_yaml_path, dump_srcml=args.dump_srcml, output_dir=args.output_dir)


if __name__ == "__main__":
    main()
